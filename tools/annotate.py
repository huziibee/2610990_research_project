"""Human semantic-reference annotation CLI. Never calls an evaluated model."""
import argparse
from collections import Counter
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from research.annotation_store import AnnotationStore
from research.integrity import read_json, verify_release
from research.reference_schema import reference_template, validate_reference
from research.input_contract import source_to_model_input


def summary(state):
    return {key: state[key] for key in ("record_id", "status", "revision", "head")}


def write_draft(store, case_id, path):
    state = store.show(case_id)
    reference = state["reference"] or reference_template(case_id, state["approved_route"])
    envelope = {"document_type": "UNVERIFIED_HUMAN_EDITABLE_DRAFT", "record_id": case_id,
                "expected_head": state["head"], "reference": reference}
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("x", encoding="utf-8") as handle:
        handle.write(json.dumps(envelope, indent=2, ensure_ascii=False) + "\n")
    return path


def parser_for_cli():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, default=ROOT / "annotation/workspace")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("init", help="Pin all 100 originals and create blank editable drafts without overwriting any")
    sub.add_parser("status", help="Counts only; no hidden semantic content printed")
    sub.add_parser("list")
    for name in ("show", "history"):
        command = sub.add_parser(name)
        command.add_argument("case_id")
        command.add_argument("--json", action="store_true")
    command = sub.add_parser("draft", help="Create a new editable draft at the current immutable head")
    command.add_argument("case_id")
    command.add_argument("--output", type=Path, required=True)
    for name in ("validate", "submit", "revise"):
        command = sub.add_parser(name)
        command.add_argument("case_id")
        command.add_argument("--file", type=Path, required=True, help="Draft envelope generated by init/draft")
        if name != "validate":
            command.add_argument("--actor", required=True, help="Actual stable preparer identity; never a fabricated reviewer")
            command.add_argument("--provenance", choices=["human", "model_candidate"], default="human")
    for name in ("adopt", "verify", "resolve", "approve"):
        command = sub.add_parser(name)
        command.add_argument("case_id")
        command.add_argument("--actor", required=True)
        command.add_argument("--head", required=True, help="Exact head from show/list; rejects stale review")
        notes = command.add_mutually_exclusive_group(required=True)
        notes.add_argument("--notes")
        notes.add_argument("--notes-file", type=Path)
        if name == "verify":
            command.add_argument("--decision", choices=["approve", "disagree"], required=True)
        if name == "resolve":
            command.add_argument("--disagreement-id", action="append", required=True)
    command = sub.add_parser("export", help="Write an exclusive versioned snapshot, separating candidates from final references")
    command.add_argument("--version", required=True)
    command.add_argument("--require-complete", action="store_true", help="Fail unless every one of the 100 references is final approved")
    return parser


def main(argv=None):
    args = parser_for_cli().parse_args(argv)
    verify_release(ROOT / "Data")
    store = AnnotationStore(args.workspace)
    if args.command == "init":
        cases = store.initialize(ROOT / "Data/data/source_100.jsonl",
                                 ROOT / "Data/data/author_approved_route_gold_100.jsonl",
                                 ROOT / "annotation/semantic_reference_template_100.jsonl")
        if [row["record_id"] for row in cases] != [f"CA-{i:04d}" for i in range(1, 101)]:
            raise ValueError("Production annotation workspace must contain all 100 current release IDs")
        made = 0
        for row in cases:
            path = args.workspace / "drafts" / (row["record_id"] + ".json")
            if not path.exists():
                write_draft(store, row["record_id"], path)
                made += 1
        print(json.dumps({"case_count": len(cases), "new_blank_drafts": made,
                          "draft_directory": str(args.workspace / "drafts"), "gold_created": False}, indent=2))
    elif args.command in ("status", "list"):
        rows = store.list_cases()
        value = rows if args.command == "list" else {"case_count": len(rows), "states": dict(Counter(row["status"] for row in rows)),
                                                      "gold_export_ready": len(rows) == 100 and all(row["status"] == "FINAL_APPROVED" for row in rows)}
        print(json.dumps(value, indent=2))
    elif args.command == "show":
        state = store.show(args.case_id)
        if args.json:
            print(json.dumps(state, indent=2, ensure_ascii=False))
        else:
            source = state["source"]
            print(f"{args.case_id} | {state['status']} | revision {state['revision']}\nHead: {state['head']}")
            for label, field in (("Original utterance", "command"), ("Scene", "scene_context"),
                                 ("Capabilities", "capability_context")):
                print(f"\n{label}:\n{source[field]}")
            print("\nOriginal dialogue:")
            print("\n".join(source["dialogue_history"]) or "[No prior dialogue supplied]")
            print("\nApproved route (locked): " + state["approved_route"]["terminal_strategy"])
            print("Approved strategy sequence: " + json.dumps(state["approved_route"]["strategy_sequence"]))
            print("\nPrepared semantic reference:\n" + json.dumps(state["reference"], indent=2, ensure_ascii=False))
            if state["disagreements"]:
                print("\nOpen disagreements:\n" + json.dumps(state["disagreements"], indent=2, ensure_ascii=False))
    elif args.command == "history":
        print(json.dumps(store.history(args.case_id), indent=2, ensure_ascii=False))
    elif args.command == "draft":
        print(write_draft(store, args.case_id, args.output))
    elif args.command in ("validate", "submit", "revise"):
        envelope = read_json(args.file)
        if (set(envelope) != {"document_type", "record_id", "expected_head", "reference"}
                or envelope["document_type"] != "UNVERIFIED_HUMAN_EDITABLE_DRAFT"
                or envelope["record_id"] != args.case_id):
            raise ValueError("Use a draft envelope from this annotation CLI; its case identity is immutable")
        state = store.show(args.case_id)
        if envelope["expected_head"] != state["head"]:
            raise ValueError("Draft is stale: use draft to create a fresh file and reconcile changes")
        if args.command == "validate":
            validate_reference(envelope["reference"], source_to_model_input(state["source"]), state["approved_route"])
            print("Structurally/contextually valid; semantic correctness and gold status are NOT established.")
        else:
            method = store.prepare if args.command == "submit" else store.revise
            print(json.dumps(summary(method(args.case_id, envelope["reference"], args.actor,
                                            provenance=args.provenance, expected_head=envelope["expected_head"])), indent=2))
    elif args.command in ("adopt", "verify", "resolve", "approve"):
        notes = args.notes if args.notes is not None else args.notes_file.read_text(encoding="utf-8")
        kwargs = {"notes": notes, "expected_head": args.head}
        if args.command == "verify":
            kwargs["decision"] = args.decision
        elif args.command == "resolve":
            kwargs["disagreement_ids"] = args.disagreement_id
        state = getattr(store, args.command)(args.case_id, args.actor, **kwargs)
        print(json.dumps(summary(state), indent=2))
    elif args.command == "export":
        print(json.dumps(store.export(args.version, require_complete=args.require_complete), indent=2))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ValueError, FileNotFoundError, FileExistsError) as exc:
        print("Annotation command rejected: " + str(exc), file=sys.stderr)
        raise SystemExit(2)
